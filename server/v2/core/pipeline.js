/**
 * Command Execution Pipeline Primitive for V2.
 *
 * Unified Atomic Flow with PostgreSQL Driver:
 * 1. Pre-validation
 * 2. ONE Atomic PostgreSQL Transaction (`pgDriver.withTransaction`):
 *    a. Claim idempotency ownership (`tx.idempotency.claim`). Replay cached result if COMPLETED.
 *    b. Execute domain handler (`handlerFn` writing state, audit, and outbox).
 *    c. Mark idempotency COMPLETED with result inside SAME transaction (`tx.idempotency.complete`).
 *    d. Flush and await staged outbox events (`tx.flushStagedOutbox`).
 *    e. COMMIT (State + Outbox + Idempotency COMPLETED commit together).
 * 3. Scoped Post-Commit Outbox Publication:
 *    a. Publish ONLY events generated by THIS command.
 *    b. Durably update status to PUBLISHED or PUBLICATION_FAILED_RETRYABLE in DB storage.
 * 4. Return replayed/fresh result.
 */

import { TransactionContext, UnitOfWork } from './transaction.js';
import { OutboxRecorder, OutboxPublisher } from './outbox.js';
import { MemoryOutboxDriver } from '../adapters/pg-outbox.js';

export async function executePipeline({
  command,
  validateFn = null,
  handlerFn,
  idempotencyStore = null,
  featureFlags = null,
  publisherFn = null,
  txContextOverride = null,
  pgDriver = null,
}) {
  if (!command || !command.type) {
    throw new Error('Pipeline requires a valid command.');
  }

  // 1. Validation step
  if (validateFn) {
    await validateFn(command, { featureFlags });
  }

  const idempotencyKey = command.idempotencyKey;
  const actorId = command.actor?.actorId;

  // --- PRODUCTION PATH using PgDriver ---
  if (pgDriver) {
    let replayed = false;
    let executionResult = null;
    let commandOutboxRecords = [];

    // Atomic PostgreSQL transaction boundary: Idempotency claim + State Mutation + Outbox Insert + Idempotency Completion
    await pgDriver.withTransaction(async (tx) => {
      if (idempotencyKey) {
        const claimResult = await tx.idempotency.claim(idempotencyKey, command);
        if (claimResult.status === 'COMPLETED') {
          replayed = true;
          executionResult = claimResult.result;
          return; // Skip domain handler execution on replay
        }
      }

      // Execute domain handler inside active PostgreSQL transaction
      executionResult = await handlerFn({
        command,
        tx,
        outbox: tx.outbox,
      });

      // Mark idempotency COMPLETED inside the SAME atomic PostgreSQL transaction before COMMIT
      if (idempotencyKey) {
        await tx.idempotency.complete(actorId, idempotencyKey, executionResult);
      }

      // Capture staged outbox records for post-commit publication
      commandOutboxRecords = tx.outbox.getStagedRecords();
    });

    if (replayed) {
      return {
        replayed: true,
        result: executionResult,
        committedOutboxRecords: [],
        publishedEvents: [],
        publicationErrors: [],
      };
    }

    // Post-commit publication: Publish ONLY events generated by THIS command
    const publisher = new PgOutboxPublisher(pgDriver, publisherFn || (async () => {}));
    const publishResult = await publisher.publishCommitted(commandOutboxRecords);

    return {
      replayed: false,
      result: executionResult,
      committedOutboxRecords: commandOutboxRecords,
      publishedEvents: publishResult.publishedEvents,
      publicationErrors: publishResult.publicationErrors,
    };
  }

  // --- MEMORY TEST DOUBLE PATH ---
  if (idempotencyStore && idempotencyKey) {
    const claimResult = await idempotencyStore.claim(idempotencyKey, command);
    if (claimResult.status === 'COMPLETED') {
      return {
        replayed: true,
        result: claimResult.result,
      };
    }
  }

  const tx = txContextOverride || new TransactionContext();
  const outbox = new OutboxRecorder();
  const uow = new UnitOfWork(tx, outbox);

  try {
    const result = await uow.execute(async (activeTx, activeOutbox) => {
      return await handlerFn({
        command,
        tx: activeTx,
        outbox: activeOutbox,
      });
    });

    const committedOutboxRecords = outbox.getCommittedOutboxRecords();
    const publisher = new OutboxPublisher(new MemoryOutboxDriver(), publisherFn || (async () => {}));
    const publishResult = await publisher.publishCommitted(committedOutboxRecords);

    if (idempotencyStore && idempotencyKey) {
      await idempotencyStore.complete(actorId, idempotencyKey, result);
    }

    return {
      replayed: false,
      result,
      committedOutboxRecords,
      publishedEvents: publishResult.publishedEvents,
      publicationErrors: publishResult.publicationErrors,
    };
  } catch (err) {
    if (idempotencyStore && idempotencyKey) {
      await idempotencyStore.fail(actorId, idempotencyKey, err);
    }
    throw err;
  }
}
